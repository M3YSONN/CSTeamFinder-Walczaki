CREATE TABLE IF NOT EXISTS MAPY (
    id_mapy SERIAL PRIMARY KEY,
    nazwa_mapy VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS POZYCJE (
    id_pozycji SERIAL PRIMARY KEY,
    id_mapy INTEGER,
    nazwa_pozycji VARCHAR(100),
    FOREIGN KEY (id_mapy) REFERENCES MAPY(id_mapy)
);

CREATE TABLE IF NOT EXISTS GRACZE (
    id_gracza INTEGER PRIMARY KEY,
    imie VARCHAR(50),
    nazwisko VARCHAR(50),
    nick VARCHAR(50),
    wiek INTEGER,
    kraj VARCHAR(50),
    rating DECIMAL(5,2),
    rola VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS GRACZ_POZYCJE (
    id_gracza INTEGER,
    id_pozycji INTEGER,
    PRIMARY KEY (id_gracza, id_pozycji),
    FOREIGN KEY (id_gracza) REFERENCES GRACZE(id_gracza),
    FOREIGN KEY (id_pozycji) REFERENCES POZYCJE(id_pozycji)
);

